                      marginTop: '12px',
                      padding: '10px 14px',
                      borderRadius: '10px',
                      background: 'rgba(201, 242, 107, 0.25)',
                      border: '1px solid rgba(19, 33, 28, 0.1)',
                      fontSize: '12.5px',
                      color: '#13211C',
                      fontWeight: 600,
                      lineHeight: 1.45
